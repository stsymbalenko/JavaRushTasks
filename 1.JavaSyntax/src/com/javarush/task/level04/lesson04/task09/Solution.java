package com.javarush.task.level04.lesson04.task09;

/* Светофор
Работа светофора для пешеходов запрограммирована следующим образом: в начале каждого часа в течение трех минут горит зеленый сигнал,
затем в течение одной минуты — желтый, а потом в течение одной минуты — красный, затем опять зеленый горит три минуты и т. д.
Ввести с клавиатуры вещественное число t, означающее время в минутах, прошедшее с начала очередного часа.
Определить, сигнал какого цвета горит для пешеходов в этот момент.
Результат вывести на экран в следующем виде:
"зеленый" - если горит зеленый цвет, "желтый" - если горит желтый цвет, "красный" - если горит красный цвет.
Пример для числа 2.5:
зеленый
Пример для числа 3:
желтый
Пример для числа 4:
красный
Пример для числа 5:
зеленый
*/

import java.io.*;

public class Solution
{
    public static void main(String[] args) throws Exception
    {
        //напишите тут ваш код
        BufferedReader reader = new BufferedReader(new InputStreamReader(System.in));
        double i = Double.parseDouble(reader.readLine());
        if (i%5<3)
            System.out.println("зеленый");
        if ((i%5 <4) && (i>=3))
        System.out.println("желтый");
        if ((i%5 <5) && (i>=4))
        System.out.println("красный");
    }
}

//Объяснение : весь цыкл работы светлофора за 5 минут (цыкл смены всех цветов), поэтому узнаем остаток от деления на 5.
// Если остаток менее 3 то будет зеленый цвет. Если менее 4 но более и равен 3 - то желтый. Если менее 5 но более равен 4 - то красный.